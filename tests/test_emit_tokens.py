"""Tests for source/skills/build-deck/scripts/emit_tokens.py"""
import contextlib
import io
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import unittest

_SCRIPTS_DIR = os.path.join(
    os.path.dirname(__file__), "..", "source", "skills", "build-deck", "scripts",
)
sys.path.insert(0, os.path.abspath(_SCRIPTS_DIR))

import emit_tokens  # noqa: E402

BRAND = {
    "fidelity": "brand",
    "fonts": {"heading": "Georgia", "body": "Calibri"},
    "colours": {
        "accent": "#4F81BD",
        "accent2": "#C0504D",
        "ink": "#101010",
        "paper": "#FFFFFF",
    },
}
HEX6 = re.compile(r"^[0-9A-F]{6}$")
PRESENTED = {"display": 96.0, "title": 60.0, "h1": 40.0, "body": 24.0, "caption": 16.0}


class BuildTokensTest(unittest.TestCase):
    def test_roles_are_six_hex_without_hash(self):
        colours = emit_tokens.build_tokens(BRAND)["colours"]
        self.assertEqual(set(colours), {"ink", "paper", "accent", "muted"})
        for value in colours.values():
            self.assertRegex(value, HEX6)
        self.assertEqual(colours["accent"], "4F81BD")
        self.assertEqual(colours["muted"], "C0504D")

    def test_presented_scale(self):
        self.assertEqual(emit_tokens.build_tokens(BRAND)["scale"], PRESENTED)

    def test_read_scale(self):
        self.assertEqual(emit_tokens.build_tokens(BRAND, "read")["scale"]["body"], 18.0)

    def test_register_passthrough(self):
        hybrid = emit_tokens.build_tokens(BRAND, "hybrid")
        self.assertEqual(hybrid["scale"]["body"], 24.0)
        self.assertEqual(hybrid["register"], "hybrid")
        self.assertEqual(emit_tokens.build_tokens(BRAND, "presented live")["scale"]["body"], 24.0)
        self.assertEqual(
            emit_tokens.build_tokens(BRAND, "read without a narrator")["scale"]["body"], 18.0
        )
        omitted = emit_tokens.build_tokens(BRAND, None)
        self.assertEqual(omitted["scale"]["body"], 24.0)
        self.assertEqual(omitted["register"], "presented")
        self.assertEqual(emit_tokens.build_tokens(BRAND, "   ")["register"], "presented")

    def test_margins_in_inches(self):
        data = emit_tokens.build_tokens(BRAND)
        self.assertGreater(data["margins"]["x"], 0.4)
        self.assertLess(data["margins"]["x"], 0.8)
        self.assertEqual(data["margins"]["top"], data["margins"]["bottom"])
        self.assertEqual(data["slide"], {"w": 13.333, "h": 7.5})

    def test_fonts_and_palette(self):
        data = emit_tokens.build_tokens(BRAND)
        self.assertEqual(data["fonts"], {"heading": "Georgia", "body": "Calibri"})
        self.assertEqual(data["palette"]["accent2"], "C0504D")

    def test_template_fidelity_refused(self):
        with self.assertRaises(emit_tokens.TokenError):
            emit_tokens.build_tokens({**BRAND, "fidelity": "template"})


class ToJsTest(unittest.TestCase):
    def test_to_js_shape(self):
        text = emit_tokens.to_js(emit_tokens.build_tokens(BRAND))
        self.assertTrue(text.startswith("// Generated by emit_tokens.py"))
        self.assertIn("module.exports = T;", text)
        self.assertIn("T.loadPptxgen", text)
        self.assertIn('require("pptxgenjs")', text)
        colours_block = text[text.index('"colours"'):text.index('"palette"')]
        self.assertNotIn("#", colours_block)


class CliTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp(prefix="slides-emit-tokens-")
        self.brand_path = os.path.join(self.tmp, "brand.json")
        with open(self.brand_path, "w", encoding="utf-8") as fh:
            json.dump(BRAND, fh)

    def tearDown(self):
        shutil.rmtree(self.tmp, ignore_errors=True)

    def test_cli_writes_cjs(self):
        out = os.path.join(self.tmp, "tokens.cjs")
        buf = io.StringIO()
        with contextlib.redirect_stdout(buf):
            code = emit_tokens.main([self.brand_path, "--out", out])
        self.assertEqual(code, 0)
        self.assertIn("wrote", buf.getvalue())
        with open(out, encoding="utf-8") as fh:
            self.assertTrue(fh.read().startswith("// Generated by emit_tokens.py"))

    def test_cli_writes_json(self):
        out = os.path.join(self.tmp, "tokens.json")
        with contextlib.redirect_stdout(io.StringIO()):
            self.assertEqual(emit_tokens.main([self.brand_path, "--out", out]), 0)
        with open(out, encoding="utf-8") as fh:
            data = json.load(fh)
        self.assertEqual(
            set(data),
            {"register", "fonts", "colours", "palette", "scale", "slide", "margins", "shape"},
        )

    def test_cli_template_fidelity_exits_1(self):
        path = os.path.join(self.tmp, "template-brand.json")
        with open(path, "w", encoding="utf-8") as fh:
            json.dump({**BRAND, "fidelity": "template"}, fh)
        err = io.StringIO()
        with contextlib.redirect_stderr(err):
            code = emit_tokens.main([path, "--out", os.path.join(self.tmp, "t.cjs")])
        self.assertEqual(code, 1)
        self.assertIn("error:", err.getvalue())

    @unittest.skipUnless(shutil.which("node"), "node not installed")
    def test_node_can_require_beneath_type_module(self):
        out = os.path.join(self.tmp, "tokens.cjs")
        with contextlib.redirect_stdout(io.StringIO()):
            emit_tokens.main([self.brand_path, "--out", out])
        with open(os.path.join(self.tmp, "package.json"), "w", encoding="utf-8") as fh:
            json.dump({"type": "module"}, fh)
        check = os.path.join(self.tmp, "check.cjs")
        with open(check, "w", encoding="utf-8") as fh:
            fh.write(
                'const T = require("./tokens.cjs");\n'
                "console.log(T.colours.accent, T.scale.body);\n"
            )
        proc = subprocess.run(["node", check], capture_output=True, text=True, cwd=self.tmp)
        self.assertEqual(proc.returncode, 0, proc.stderr)
        self.assertEqual(proc.stdout.strip(), "4F81BD 24")


if __name__ == "__main__":
    unittest.main()
